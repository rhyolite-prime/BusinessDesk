BEGIN;
CREATE TABLE core_company_profiles (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid NOT NULL UNIQUE REFERENCES tenants(id),
    company_name varchar(200) NOT NULL DEFAULT '' CHECK (btrim(company_name) <> ''),
    country_name varchar(100) NOT NULL DEFAULT '',
    city_name varchar(160) NOT NULL DEFAULT '',
    phone_no varchar(50) NOT NULL DEFAULT '',
    address varchar(1000) NOT NULL DEFAULT '',
    country uuid DEFAULT NULL,
    company_tin varchar(100) NOT NULL DEFAULT '',
    email varchar(254) NOT NULL DEFAULT '',
    first_month_of_fiscal_year integer NOT NULL DEFAULT 1 CHECK (first_month_of_fiscal_year BETWEEN 1 AND 12),
    vat_no varchar(100) NOT NULL DEFAULT '',
    employer_social_security_no varchar(100) NOT NULL DEFAULT '',
    pay_social_security_fund boolean NOT NULL DEFAULT false,
    social_security_fund_employee_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (social_security_fund_employee_rate BETWEEN 0 AND 100),
    social_security_fund_employer_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (social_security_fund_employer_rate BETWEEN 0 AND 100),
    pay_provident_fund boolean NOT NULL DEFAULT false,
    provident_fund_employee_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (provident_fund_employee_rate BETWEEN 0 AND 100),
    provident_fund_employer_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (provident_fund_employer_rate BETWEEN 0 AND 100),
    provident_fund_treat_as_social_security_fund boolean NOT NULL DEFAULT false,
    provident_fund_tax_employer_portion boolean NOT NULL DEFAULT false,
    pay_second_provident_or_others boolean NOT NULL DEFAULT false,
    second_provident_employee_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (second_provident_employee_rate BETWEEN 0 AND 100),
    second_provident_employer_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (second_provident_employer_rate BETWEEN 0 AND 100),
    treat_second_provident_as_ssf boolean NOT NULL DEFAULT false,
    second_provident_tax_employer_portion boolean NOT NULL DEFAULT false,
    overtime_percentage_on_basic_salary boolean NOT NULL DEFAULT false,
    overtime_percentage_on_daily_wage boolean NOT NULL DEFAULT false,
    default_currency_id uuid DEFAULT NULL REFERENCES core_currencies(id),
    mail_host_name varchar(255) NOT NULL DEFAULT '',
    is_ssl_enabled boolean NOT NULL DEFAULT false,
    port_number integer NOT NULL DEFAULT 0 CHECK (port_number BETWEEN 0 AND 65535),
    primary_email_address varchar(254) NOT NULL DEFAULT '',
    is_tax_levies_inclusive boolean NOT NULL DEFAULT false,
    approve_invoice_before_payment boolean NOT NULL DEFAULT false,
    company_logo_url varchar(2048) NOT NULL DEFAULT '',
    enforce_ou boolean NOT NULL DEFAULT false,
    email_password_encrypted text,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id uuid NOT NULL REFERENCES users(id),
    last_modified_at timestamptz,
    last_modified_by_user_id uuid REFERENCES users(id),
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    deleted_by_user_id uuid REFERENCES users(id)
);
CREATE INDEX ix_company_profiles_live_default_currency ON core_company_profiles(default_currency_id) WHERE is_deleted=false AND default_currency_id IS NOT NULL;
COMMIT;
